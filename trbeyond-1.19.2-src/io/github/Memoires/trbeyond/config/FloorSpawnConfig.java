   public static final int FLOORS = 19;

   public FloorSpawnConfig(Builder builder) {
      this.floorSpawns = new ConfigValue[19];
      this.treasureFloorSpawns = new ConfigValue[19];

      for (int i = 0; i < 19; i++) {
         int floorNumber = i + 2;
         builder.push("floor" + floorNumber);
         this.floorSpawns[i] = builder.comment("List of mobs and weights for floor " + floorNumber + " format: modid:entity,weight,min,max")
            .defineList("floorMobs", this.floor_list.get(i), o -> o instanceof String);
         this.treasureFloorSpawns[i] = builder.comment(
               "List of mobs and weights for treasure rooms on floor " + floorNumber + " format: modid:entity,weight,min,max"
            )
            .defineList("treasureFloorMobs", this.treasure_floor_list.get(i), o -> o instanceof String);
         builder.pop();
      }

      this.floorSpawnsRandomLists.clear();
      this.treasureFloorSpawnsRandomLists.clear();

      for (int i = 0; i < 100; i++) {
         this.floorSpawnsRandomLists.add(null);
         this.treasureFloorSpawnsRandomLists.add(null);
      }
   }

   public List<? extends String> getFloorRawEntries(int floorNumber) {
      return floorNumber >= 1 && floorNumber <= 19 ? (List)this.floorSpawns[floorNumber - 2].get() : Collections.emptyList();
   }

   public List<? extends String> getTreasureFloorRawEntries(int floorNumber) {
      return floorNumber >= 1 && floorNumber <= 19 ? (List)this.treasureFloorSpawns[floorNumber - 2].get() : Collections.emptyList();
   }

   private WeightedRandomList<Wrapper<FloorSpawnConfig.SpawnParams>> parseWeightedEntries(List<? extends String> entries) {
      List<Wrapper<FloorSpawnConfig.SpawnParams>> list = new ArrayList<>();

      for (String entry : entries) {
         String[] parts = entry.split(",");
         if (parts.length == 4) {
            ResourceLocation rl = new ResourceLocation(parts[0].trim());
            EntityType<?> type = (EntityType<?>)ForgeRegistries.ENTITY_TYPES.getValue(rl);
            if (type != null) {
               try {
                  int weight = Integer.parseInt(parts[1].trim());
                  int min = Integer.parseInt(parts[2].trim());
                  int max = Integer.parseInt(parts[3].trim());
                  list.add(WeightedEntry.wrap(new FloorSpawnConfig.SpawnParams(type, min, max), weight));
               } catch (NumberFormatException var11) {
               }
            }
         }
      }

      return WeightedRandomList.create(list);
   }

   public WeightedRandomList<Wrapper<FloorSpawnConfig.SpawnParams>> getFloorRandomEntryList(int floorNumber) {
      int floorIndex = floorNumber - 2;
      if (this.floorSpawnsRandomLists.get(floorIndex) == null) {
         this.floorSpawnsRandomLists.set(floorIndex, this.parseWeightedEntries(this.getFloorRawEntries(floorNumber)));
      }

      return this.floorSpawnsRandomLists.get(floorIndex);
   }

   public WeightedRandomList<Wrapper<FloorSpawnConfig.SpawnParams>> getTreasureFloorRandomEntryList(int floorNumber) {
      int floorIndex = floorNumber - 2;
      if (this.treasureFloorSpawnsRandomLists.get(floorIndex) == null) {
         this.treasureFloorSpawnsRandomLists.set(floorIndex, this.parseWeightedEntries(this.getTreasureFloorRawEntries(floorNumber)));
      }

      return this.treasureFloorSpawnsRandomLists.get(floorIndex);
   }

